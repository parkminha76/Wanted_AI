def get_scenarios(level: int) -> list[dict]:
    """해당 Level의 시나리오 목록을 반환한다."""
    if level not in SCENARIOS:
        raise ValueError(f"존재하지 않는 level입니다: {level}")

    return SCENARIOS[level]


def select_random_scenario(level: int) -> dict:
    """해당 Level의 6개 시나리오 중 하나를 무작위로 선택한다."""
    return random.choice(get_scenarios(level))